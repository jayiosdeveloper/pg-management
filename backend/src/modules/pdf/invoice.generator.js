const PDFDocument = require('pdfkit');

const fmtCurrency = (n) => `INR ${Number(n || 0).toFixed(2)}`;

/**
 * Streams a PDF buffer for a single tenant invoice covering a billing month.
 * Returns a Buffer.
 */
const generate = ({ tenant, bills, payments, invoiceNumber, billingMonth, totals }) =>
  new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 50 });
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    // Header
    doc.fillColor('#0B1437').rect(0, 0, doc.page.width, 80).fill();
    doc.fillColor('#FFFFFF').fontSize(20).font('Helvetica-Bold').text('PG MANAGEMENT', 50, 28);
    doc.fontSize(11).font('Helvetica').text('Hostel & PG Billing Invoice', 50, 54);
    doc.fillColor('#22D3EE').fontSize(10).text(`Invoice #${invoiceNumber}`, 0, 32, { align: 'right', width: doc.page.width - 50 });
    doc.fillColor('#FFFFFF').text(`Month: ${billingMonth}`, 0, 50, { align: 'right', width: doc.page.width - 50 });

    doc.moveDown(2);
    doc.fillColor('#111111').fontSize(11);

    // Tenant block
    const u = tenant.user || {};
    const r = tenant.room || {};
    doc.font('Helvetica-Bold').text('Billed to', 50, 110);
    doc.font('Helvetica').text(u.full_name || '', 50, 126);
    if (u.user_code) doc.text(`User ID: ${u.user_code}`);
    if (u.phone) doc.text(`Phone: ${u.phone}`);
    if (u.email) doc.text(`Email: ${u.email}`);

    doc.font('Helvetica-Bold').text('Accommodation', 320, 110);
    doc.font('Helvetica');
    if (r.room_number) doc.text(`Room: ${r.room_number}`, 320);
    if (tenant.bed?.bed_label) doc.text(`Bed: ${tenant.bed.bed_label}`, 320);
    if (tenant.joining_date) doc.text(`Joined: ${tenant.joining_date}`, 320);

    // Table
    const tableTop = 220;
    doc.moveTo(50, tableTop - 10).lineTo(545, tableTop - 10).strokeColor('#CCCCCC').stroke();
    doc.font('Helvetica-Bold').fillColor('#0B1437').fontSize(11);
    doc.text('Category', 50, tableTop);
    doc.text('Description', 160, tableTop);
    doc.text('Due', 360, tableTop);
    doc.text('Amount', 430, tableTop, { width: 100, align: 'right' });

    doc.moveTo(50, tableTop + 14).lineTo(545, tableTop + 14).strokeColor('#CCCCCC').stroke();
    doc.font('Helvetica').fillColor('#111111');
    let y = tableTop + 24;
    for (const b of bills) {
      doc.text(b.category.replace(/^./, c => c.toUpperCase()), 50, y);
      doc.text(b.description || '-', 160, y, { width: 190 });
      doc.text(b.due_date, 360, y);
      doc.text(fmtCurrency(b.amount), 430, y, { width: 100, align: 'right' });
      y += 22;
      if (y > 700) { doc.addPage(); y = 80; }
    }

    // Totals
    y += 12;
    doc.moveTo(50, y).lineTo(545, y).strokeColor('#CCCCCC').stroke();
    y += 10;
    doc.font('Helvetica-Bold').text('Total billed', 360, y);
    doc.text(fmtCurrency(totals.totalBilled), 430, y, { width: 100, align: 'right' });
    y += 18;
    doc.font('Helvetica').text('Paid', 360, y);
    doc.text(fmtCurrency(totals.totalPaid), 430, y, { width: 100, align: 'right' });
    y += 18;
    doc.font('Helvetica-Bold').fillColor(totals.pending > 0 ? '#EF4444' : '#16A34A').text('Pending', 360, y);
    doc.text(fmtCurrency(totals.pending), 430, y, { width: 100, align: 'right' });

    // Payments history
    y += 32;
    if (payments && payments.length > 0) {
      doc.fillColor('#0B1437').font('Helvetica-Bold').fontSize(12).text('Payment history', 50, y);
      y += 18;
      doc.font('Helvetica').fontSize(10).fillColor('#111111');
      for (const p of payments) {
        const when = (p.paid_at || '').slice(0, 10);
        doc.text(`${when}  •  ${p.method || 'cash'}  •  ${fmtCurrency(p.amount)}${p.reference ? '  • ref ' + p.reference : ''}`, 50, y);
        y += 14;
        if (y > 760) { doc.addPage(); y = 60; }
      }
    }

    // Footer
    const fy = doc.page.height - 60;
    doc.fillColor('#94A3B8').fontSize(9).font('Helvetica')
      .text('Generated by PG Management ERP', 50, fy, { align: 'center', width: doc.page.width - 100 });

    doc.end();
  });

module.exports = { generate };
